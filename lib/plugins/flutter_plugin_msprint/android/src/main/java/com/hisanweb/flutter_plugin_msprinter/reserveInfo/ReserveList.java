package com.hisanweb.flutter_plugin_msprinter.reserveInfo;

import java.util.List;


public class ReserveList {

    private String machineCode;
    private String tableType;
    private String howManyPeople;
    private String reserveTime;
    private String reserveNo;
    private String reserveNumber;
    private String queryLink;

    public String getMachineCode() {
        return machineCode;
    }

    public void setMachineCode(String machineCode) {
        this.machineCode = machineCode;
    }

    public String getTableType() {
        return tableType;
    }

    public void setTableType(String tableType) {
        this.tableType = tableType;
    }

    public String getHowManyPeople() {
        return howManyPeople;
    }

    public void setHowManyPeople(String howManyPeople) {
        this.howManyPeople = howManyPeople;
    }

    public String getReserveTime() {
        return reserveTime;
    }

    public void setReserveTime(String reserveTime) {
        this.reserveTime = reserveTime;
    }

    public String getReserveNo() {
        return reserveNo;
    }

    public void setReserveNo(String reserveNo) {
        this.reserveNo = reserveNo;
    }

    public String getReserveNumber() {
        return reserveNumber;
    }

    public void setReserveNumber(String reserveNumber) {
        this.reserveNumber = reserveNumber;
    }

    public String getQueryLink() {
        return queryLink;
    }

    public void setQueryLink(String queryLink) {
        this.queryLink = queryLink;
    }



}